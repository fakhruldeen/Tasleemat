def clean_file(path: pathlib.Path):
    text = path.read_text(encoding="utf-8")
    original = text
    for pattern, repl in REWRITES:
        text = re.sub(pattern, repl, text)
    # Fix double spaces between Arabic characters
    text = re.sub(r"([؀-ۿ])[ \t]{2,}([؀-ۿ])", r"\1 \2", text)
    if text != original:
        path.write_text(text, encoding="utf-8")
        return True
    return False

def main():
    modified = 0
    for p in sorted(AR_FORMS.rglob("*")):
        if p.is_file() and p.suffix in (".md", ".json", ".csv"):
            if clean_file(p):
                modified += 1
    print(f"Cleaned conversational phrasing across {modified} Arabic files.")

if __name__ == "__main__":
    main()
